-- 게시글 테이블

CREATE TABLE BOARD (
	BNO NUMBER,
	TITLE VARCHAR2(200),
	CONTENT VARCHAR2(2000),
	WRITER VARCHAR2(100),
	REGDATE DATE DEFAULT SYSDATE,
	MODDATE DATE DEFAULT SYSDATE,
	CAFE_BOARD_ID NUMBER,
	CONSTRAINT SYS_C008695 CHECK ("TITLE" IS NOT NULL),
	CONSTRAINT SYS_C008696 CHECK ("WRITER" IS NOT NULL),
	CONSTRAINT SYS_C008697 CHECK ("CAFE_BOARD_ID" IS NOT NULL),
	CONSTRAINT SYS_C008698 PRIMARY KEY (BNO),
	CONSTRAINT FK_BOARD_CAFE_BOARD FOREIGN KEY (CAFE_BOARD_ID) REFERENCES CAFE_BOARD(CAFE_BOARD_ID),
	CONSTRAINT FK_BOARD_WRITER FOREIGN KEY (WRITER) REFERENCES "MEMBER"(USERNAME)
);

