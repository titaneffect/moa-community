-- 회원 테이블

CREATE TABLE "MEMBER" (
	USERNAME VARCHAR2(50),
	PASSWORD VARCHAR2(100),
	ENABLED NUMBER(1, 0) DEFAULT 1 ,
	REGDATE DATE DEFAULT SYSDATE ,
	CONSTRAINT SYS_C008652 CHECK ("PASSWORD" IS NOT NULL),
	CONSTRAINT SYS_C008653 CHECK ("ENABLED" IS NOT NULL),
	CONSTRAINT SYS_C008654 CHECK ("REGDATE" IS NOT NULL),
	CONSTRAINT SYS_C008655 PRIMARY KEY (USERNAME)
);

-- 카페 테이블

CREATE TABLE CAFE (
	CAFE_ID NUMBER,
	CAFE_NAME VARCHAR2(100),
	DESCRIPTION VARCHAR2(500),
	OWNER_USERNAME VARCHAR2(50),
	STATUS VARCHAR2(20) DEFAULT 'ACTIVE' ,
	CREATED_AT DATE DEFAULT SYSDATE ,
	UPDATED_AT DATE DEFAULT SYSDATE ,
	CONSTRAINT CK_CAFE_STATUS CHECK (STATUS IN ('ACTIVE', 'DELETED', 'SUSPENDED')),
	CONSTRAINT SYS_C008656 CHECK ("CAFE_NAME" IS NOT NULL),
	CONSTRAINT SYS_C008657 CHECK ("OWNER_USERNAME" IS NOT NULL),
	CONSTRAINT SYS_C008658 CHECK ("STATUS" IS NOT NULL),
	CONSTRAINT SYS_C008659 CHECK ("CREATED_AT" IS NOT NULL),
	CONSTRAINT SYS_C008660 CHECK ("UPDATED_AT" IS NOT NULL),
	CONSTRAINT SYS_C008662 PRIMARY KEY (CAFE_ID),
	CONSTRAINT FK_CAFE_MEMBER FOREIGN KEY (OWNER_USERNAME) REFERENCES "MEMBER"(USERNAME)
);

-- 카페 게시판 테이블

CREATE TABLE CAFE_BOARD (
	CAFE_BOARD_ID NUMBER,
	CAFE_ID NUMBER,
	BOARD_NAME VARCHAR2(100),
	BOARD_TYPE VARCHAR2(20) DEFAULT 'GENERAL' ,
	READ_ROLE VARCHAR2(20) DEFAULT 'GUEST' ,
	WRITE_ROLE VARCHAR2(20) DEFAULT 'MEMBER' ,
	DISPLAY_ORDER NUMBER DEFAULT 1 ,
	STATUS VARCHAR2(20) DEFAULT 'ACTIVE' ,
	CREATED_AT DATE DEFAULT SYSDATE ,
	UPDATED_AT DATE DEFAULT SYSDATE ,
	CONSTRAINT CK_CAFE_BOARD_STATUS CHECK (STATUS IN ('ACTIVE', 'DELETED')),
	CONSTRAINT CK_CAFE_BOARD_TYPE CHECK (BOARD_TYPE IN ('GENERAL', 'NOTICE')),
	CONSTRAINT CK_CAFE_READ_ROLE CHECK (READ_ROLE IN ('GUEST', 'MEMBER', 'MANAGER', 'OWNER')),
	CONSTRAINT CK_CAFE_WRITE_ROLE CHECK (WRITE_ROLE IN ('MEMBER', 'MANAGER', 'OWNER')),
	CONSTRAINT SYS_C008664 CHECK ("CAFE_ID" IS NOT NULL),
	CONSTRAINT SYS_C008665 CHECK ("BOARD_NAME" IS NOT NULL),
	CONSTRAINT SYS_C008666 CHECK ("BOARD_TYPE" IS NOT NULL),
	CONSTRAINT SYS_C008667 CHECK ("READ_ROLE" IS NOT NULL),
	CONSTRAINT SYS_C008668 CHECK ("WRITE_ROLE" IS NOT NULL),
	CONSTRAINT SYS_C008669 CHECK ("DISPLAY_ORDER" IS NOT NULL),
	CONSTRAINT SYS_C008670 CHECK ("STATUS" IS NOT NULL),
	CONSTRAINT SYS_C008671 CHECK ("CREATED_AT" IS NOT NULL),
	CONSTRAINT SYS_C008672 CHECK ("UPDATED_AT" IS NOT NULL),
	CONSTRAINT SYS_C008677 PRIMARY KEY (CAFE_BOARD_ID),
	CONSTRAINT UK_CAFE_BOARD_NAME UNIQUE (CAFE_ID, BOARD_NAME),
	CONSTRAINT FK_CAFE_BOARD_CAFE FOREIGN KEY (CAFE_ID) REFERENCES CAFE(CAFE_ID)
);

-- 카페 회원 테이블

CREATE TABLE CAFE_MEMBER (
	CAFE_MEMBER_ID NUMBER,
	CAFE_ID NUMBER,
	MEMBER_USERNAME VARCHAR2(50),
	CAFE_ROLE VARCHAR2(20) DEFAULT 'MEMBER' ,
	STATUS VARCHAR2(20) DEFAULT 'ACTIVE' ,
	JOINED_AT DATE DEFAULT NULL,
	CONSTRAINT CK_CAFE_MEMBER_ROLE CHECK (CAFE_ROLE IN ('OWNER', 'MANAGER', 'MEMBER')),
	CONSTRAINT CK_CAFE_MEMBER_STATUS CHECK (STATUS IN ('PENDING', 'ACTIVE', 'REJECTED', 'WITHDRAWN', 'BANNED')),
	CONSTRAINT SYS_C008680 CHECK ("CAFE_ID" IS NOT NULL),
	CONSTRAINT SYS_C008681 CHECK ("MEMBER_USERNAME" IS NOT NULL),
	CONSTRAINT SYS_C008682 CHECK ("CAFE_ROLE" IS NOT NULL),
	CONSTRAINT SYS_C008683 CHECK ("STATUS" IS NOT NULL),
	CONSTRAINT SYS_C008686 PRIMARY KEY (CAFE_MEMBER_ID),
	CONSTRAINT UK_CAFE_MEMBER UNIQUE (CAFE_ID, MEMBER_USERNAME),
	CONSTRAINT FK_CAFE_MEMBER_CAFE FOREIGN KEY (CAFE_ID) REFERENCES CAFE(CAFE_ID),
	CONSTRAINT FK_CAFE_MEMBER_MEMBER FOREIGN KEY (MEMBER_USERNAME) REFERENCES "MEMBER"(USERNAME)
);

-- 회원 권한 테이블

