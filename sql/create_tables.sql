	CONSTRAINT SYS_C008702 CHECK ("UUID" IS NOT NULL),
	CONSTRAINT SYS_C008703 CHECK ("FILE_NAME" IS NOT NULL),
	CONSTRAINT SYS_C008704 CHECK ("UPLOAD_PATH" IS NOT NULL),
	CONSTRAINT SYS_C008705 CHECK ("ATTACH_USAGE" IS NOT NULL),
	CONSTRAINT SYS_C008707 PRIMARY KEY (ANO),
	CONSTRAINT FK_BOARD_ATTACH FOREIGN KEY (BNO) REFERENCES BOARD(BNO)
