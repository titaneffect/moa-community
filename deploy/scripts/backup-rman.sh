#!/bin/bash
# Weekly full RMAN bundle. Run as root; BACKUP_PRUNE=0 previews all deletion.
set -euo pipefail
umask 077
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export TZ=Asia/Seoul
cd /home/ubuntu/deepstudy-deploy

[[ "$EUID" == "0" ]] || { echo "sudo로 실행하세요." >&2; exit 1; }
BACKUP_PRUNE=${BACKUP_PRUNE:-0}
[[ "$BACKUP_PRUNE" == "0" || "$BACKUP_PRUNE" == "1" ]]
exec 9>/run/deepstudy-rman-backup.lock
flock -n 9 || { echo "RMAN 백업이 이미 실행 중입니다."; exit 0; }
if [[ "$BACKUP_PRUNE" == "1" ]]; then
  python3 deploy/scripts/backup-store.py check-bucket
fi

# No host copy: upload directly from the persistent Oracle volume.
available_kb=$(docker exec -u oracle oracle-db df -Pk /opt/oracle/oradata | awk 'NR==2 {print $4}')
[[ "$available_kb" =~ ^[0-9]+$ ]]
if (( available_kb < 8 * 1024 * 1024 )); then
  echo "여유 공간이 8GiB 미만이어서 새 전체 백업을 중단합니다. 기존 백업은 유지합니다." >&2
  exit 1
fi

stamp=$(date +%Y%m%d-%H%M%S)
dbid=$(docker exec -i -u oracle oracle-db sqlplus -s / as sysdba <<'SQL'
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT FAILURE
SET HEADING OFF FEEDBACK OFF PAGESIZE 0 VERIFY OFF ECHO OFF
SELECT dbid FROM v$database;
EXIT;
SQL
)
dbid=$(echo "$dbid" | tr -d '\r' | sed '/^[[:space:]]*$/d;s/^[[:space:]]*//;s/[[:space:]]*$//')
[[ "$dbid" =~ ^[0-9]+$ ]]
backup_dir="/opt/oracle/oradata/rman-managed/${stamp}"
mkdir -p logs
run_log="logs/rman-${stamp}.log"
docker exec -u oracle oracle-db mkdir -p "$backup_dir"

run_rman() {
  local output
  output=$(mktemp)
  if ! docker exec -i -u oracle oracle-db rman target / | tee "$output"; then
    cat "$output" >> "$run_log"
    rm -f -- "$output"
    return 1
  fi
  cat "$output" >> "$run_log"
  if grep -Eq '^(RMAN-|ORA-)[0-9]+:' "$output"; then
    rm -f -- "$output"
    return 1
  fi
  rm -f -- "$output"
}

run_rman <<RMAN
SET CONTROLFILE AUTOBACKUP FORMAT FOR DEVICE TYPE DISK TO '${backup_dir}/%F.bkp';
RUN {
  ALLOCATE CHANNEL c1 DEVICE TYPE DISK FORMAT '${backup_dir}/%d_%T_%U.bkp';
  BACKUP DATABASE FORCE PLUS ARCHIVELOG;
  RELEASE CHANNEL c1;
}
EXIT;
RMAN

# Validate exactly the sets generated by this run, including the autobackup.
validation=$(docker exec -i -u oracle oracle-db sqlplus -s / as sysdba <<SQL
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT FAILURE
SET HEADING OFF FEEDBACK OFF PAGESIZE 0 VERIFY OFF ECHO OFF LINESIZE 200
SELECT DISTINCT 'VALIDATE BACKUPSET ' || s.recid || ';'
FROM v\$backup_set s JOIN v\$backup_piece p
ON s.set_stamp = p.set_stamp AND s.set_count = p.set_count
WHERE p.handle LIKE '${backup_dir}/%' AND p.status = 'A';
EXIT;
SQL
)
[[ "$validation" == *"VALIDATE BACKUPSET "* ]]
run_rman <<RMAN
${validation}
EXIT;
RMAN

python3 deploy/scripts/backup-store.py publish-rman --stamp "$stamp" --dbid "$dbid"

prune_args=()
if [[ "$BACKUP_PRUNE" == "1" ]]; then
  prune_args+=(--apply)
fi
python3 deploy/scripts/backup-store.py finalize-rman --stamp "$stamp" "${prune_args[@]}"
echo "RMAN 백업·검증·S3 보관 완료: ${stamp} (DBID=${dbid})"
